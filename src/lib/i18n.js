const LOCALE = { es: 'es-ES', ca: 'ca-ES' };

export function formatDate(iso, lang, { time = true } = {}) {
  if (!iso) return '';
  return new Intl.DateTimeFormat(LOCALE[lang], {
    timeZone: 'Europe/Madrid',
    day: 'numeric',
    month: 'short',
    ...(time ? { hour: '2-digit', minute: '2-digit' } : { year: 'numeric' }),
  }).format(new Date(iso));
}

export function formatLongDate(date, lang) {
  return new Intl.DateTimeFormat(LOCALE[lang], { timeZone: 'Europe/Madrid', weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' }).format(date);
}
